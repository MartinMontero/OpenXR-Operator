"""Loopback, token-gated web UI (kit §3.2 and M6; D-14 approval cards).

Security shape:
- Binds 127.0.0.1 only (serve() below; the bind gate enforces this).
- Every request requires the UI token (query param, form field, or header).
  The token is generated by the operator process and printed to the console;
  it is never written into the page or the repo.
- Every POST additionally requires an exact-match Origin allowlist — in
  Python the header is readable, which is exactly why the browser-facing
  surface lives here and not in the engine.
- Strict CSP with no third-party origins; all assets vendored locally.
- D-14: approval cards are plain language. The model's rationale is rendered
  as an untrusted quote. Raw JSON is never the approval view.
"""

from __future__ import annotations

import hmac

from flask import Flask, abort, redirect, render_template, request, url_for

from .runtime import UIRuntime

DEFAULT_ORIGINS = ("http://127.0.0.1:5000", "http://localhost:5000")


def create_app(
    runtime: UIRuntime,
    *,
    ui_token: str,
    allowed_origins: tuple[str, ...] = DEFAULT_ORIGINS,
) -> Flask:
    app = Flask(__name__)
    app.config["MAX_CONTENT_LENGTH"] = 64 * 1024

    @app.after_request
    def _headers(response):  # type: ignore[no-untyped-def]
        response.headers["Content-Security-Policy"] = (
            "default-src 'self'; img-src 'self' data:; "
            "style-src 'self' 'unsafe-inline'; script-src 'self'; "
            "frame-ancestors 'none'; base-uri 'none'"
        )
        response.headers["X-Frame-Options"] = "DENY"
        response.headers["X-Content-Type-Options"] = "nosniff"
        response.headers["Referrer-Policy"] = "no-referrer"
        return response

    @app.before_request
    def _gate() -> None:
        supplied = (
            request.args.get("token")
            or request.form.get("token")
            or request.headers.get("X-OXR-Token")
            or ""
        )
        if not hmac.compare_digest(supplied, ui_token):
            abort(401)
        if (
            request.method == "POST"
            and request.headers.get("Origin", "") not in allowed_origins
        ):
            abort(403)

    @app.get("/")
    def index():  # type: ignore[no-untyped-def]
        return render_template(
            "index.html",
            status=runtime.status(),
            pending=runtime.pending(),
            token=request.args.get("token", ""),
        )

    @app.post("/task")
    def start_task():  # type: ignore[no-untyped-def]
        task = request.form.get("task", "").strip()
        if task:
            runtime.start_task(task)
        return redirect(url_for("index", token=request.form.get("token", "")))

    @app.post("/approve")
    def approve():  # type: ignore[no-untyped-def]
        request_id = request.form.get("id", "")
        approved = request.form.get("approved") == "1"
        if not runtime.decide(request_id, approved):
            abort(404)
        return redirect(url_for("index", token=request.form.get("token", "")))

    @app.get("/status")
    def status():  # type: ignore[no-untyped-def]
        return runtime.status()

    return app


def serve(runtime: UIRuntime, *, ui_token: str, port: int = 5000) -> None:
    """Loopback only. The browser never touches the engine port."""
    create_app(runtime, ui_token=ui_token).run(host="127.0.0.1", port=port)
